"""DynaDWDP configuration and operating modes."""

from __future__ import annotations

import os
from dataclasses import dataclass
from enum import Enum
from typing import Optional


class DynaDWDPMode(str, Enum):
    """Operating modes spanning the accuracy-vs-prefetch-cost spectrum.

    FORCED: prefetch set strictly bounded by the communication budget; tokens
        routed to missing experts are served by local replacement experts.
        Deterministic prefetch cost, largest quality impact, no fallback.
    SOFT: minimal set plus `extra_experts` additional high-probability experts;
        missing experts still handled by local replacement, no fallback.
    HIGH_PRECISION: set generated by the quality constraint; if the fraction
        of tokens routed to missing experts exceeds `eta`, missing experts are
        synchronously fetched (fallback on the critical path).
    """

    OFF = "off"
    FORCED = "forced"
    SOFT = "soft"
    HIGH_PRECISION = "high_precision"


@dataclass
class DynaDWDPConfig:
    # dynamic routing: per-token activation count
    k_min: int | None = None  # None = follow k_max (static); explicit value enables dynamic-k
    k_max: int = 8
    epsilon: float = 0.15          # mass tolerance: select m until cum >= 1 - epsilon
    tau: float = 0.5               # gap criterion: p_m - p_{m+1} >= tau * p_m
    # predictor strength: THE external knob for prefetch volume.
    #   s in [0, 1]; prefetch count N = round(R * (1 - s)) where R = remote
    #   expert count. s=0 -> full prefetch (DWDP-Full equivalent); higher s
    #   -> fewer prefetched experts, lower weight-byte volume, higher demands
    #   on prediction quality (unhit tokens are served by local replacement).
    predictor_strength: float = 0.5
    decode_threshold: int = 512    # batch tokens below this = decode -> full ready set
                                  # (predictor features are prefill-shaped; decode
                                  #  batches are OOD -> keep DWDP-Full semantics)
    # fallback (HIGH_PRECISION mode only)
    eta: float = 0.02              # max missing-expert token fraction
    max_sync_fetches: int = 16     # per layer per forward, HIGH_PRECISION only
    # predictor
    calibrate: bool = False        # online training of lookahead heads
    lr: float = 1e-3
    corrector_lambda: float = 0.5  # mix: lambda*head + (1-lambda)*histogram
    head_cache_dir: str = ""
    head_warmup: int = 200         # blend the head in after this many samples

    # ---- retired fields (parsed for CLI compatibility, no longer used) ----
    delta: float = 0.98
    extra_experts: int = 8
    max_prefetch_experts: int = 0
    calib_min_steps: int = 2000

    @property
    def mode(self) -> DynaDWDPMode:
        return self._mode

    @classmethod
    def from_server_args(cls, sa) -> "DynaDWDPConfig":
        mode = DynaDWDPMode(getattr(sa, "dynadwdp_mode", "off") or "off")
        cfg = cls(
            k_min=getattr(sa, "dynadwdp_k_min", None),
            k_max=getattr(sa, "dynadwdp_k_max", 8),
            epsilon=getattr(sa, "dynadwdp_epsilon", 0.15),
            tau=getattr(sa, "dynadwdp_tau", 0.5),
            predictor_strength=getattr(sa, "dynadwdp_predictor_strength", 0.5),
            eta=getattr(sa, "dynadwdp_eta", 0.02),
            max_sync_fetches=getattr(sa, "dynadwdp_max_sync_fetches", 16),
            calibrate=getattr(sa, "dynadwdp_calibrate", False),
            lr=getattr(sa, "dynadwdp_lr", 1e-3),
            corrector_lambda=getattr(sa, "dynadwdp_corrector_lambda", 0.5),
            head_cache_dir=getattr(sa, "dynadwdp_head_cache_dir", "") or "",
            max_prefetch_experts=getattr(sa, "dynadwdp_max_prefetch_experts", 0),
        )
        cfg.predictor_strength = min(max(cfg.predictor_strength, 0.0), 1.0)
        # exp5: allow forcing the prefill (predictor) path for evaluation;
        # default 512 keeps upstream behavior
        _dt = os.environ.get('DYNADWDP_DECODE_THRESHOLD')
        if _dt:
            cfg.decode_threshold = int(_dt)
        cfg._mode = mode
        model_dir = getattr(sa, "model_path", "model")
        if not cfg.head_cache_dir:
            cfg.head_cache_dir = os.path.join(
                "/tmp", "dynadwdp_heads", os.path.basename(model_dir.rstrip("/"))
            )
        return cfg
